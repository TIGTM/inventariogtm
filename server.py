@contextmanager
def connection():
    with psycopg.connect(DATABASE_URL, row_factory=dict_row) as conn:
        conn.execute("SELECT set_config('app.actor', %s, true)", (json.dumps(AUDIT.get()),))
        yield conn


def init_db():
    with connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS equipamentos (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                patrimonio TEXT NOT NULL,
                dados JSONB NOT NULL,
                setor TEXT NOT NULL DEFAULT 'TI',
                criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS movimentacoes (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                equipamento_id BIGINT REFERENCES equipamentos(id) ON DELETE CASCADE,
                dados JSONB NOT NULL,
                setor TEXT NOT NULL DEFAULT 'TI',
                criada_em TIMESTAMPTZ NOT NULL DEFAULT now()
            )
        """)
        conn.execute("ALTER TABLE equipamentos ADD COLUMN IF NOT EXISTS setor TEXT NOT NULL DEFAULT 'TI'")
        conn.execute("ALTER TABLE movimentacoes ADD COLUMN IF NOT EXISTS setor TEXT NOT NULL DEFAULT 'TI'")
        conn.execute("ALTER TABLE equipamentos ADD COLUMN IF NOT EXISTS excluido BOOLEAN NOT NULL DEFAULT false")
        conn.execute("ALTER TABLE equipamentos DROP CONSTRAINT IF EXISTS equipamentos_patrimonio_key")
        conn.execute("DROP INDEX IF EXISTS equipamentos_setor_patrimonio_unique")
        conn.execute("CREATE UNIQUE INDEX equipamentos_setor_patrimonio_unique ON equipamentos (setor, patrimonio) WHERE NOT excluido")


def equipment_row(row):
    return {**row["dados"], "id": str(row["id"])}


def history_row(row):
    return {**row["dados"], "id": str(row["id"]), "histid": str(row["id"]), "equipamentoId": str(row["equipamento_id"])}


def clean_status(value):
    return {"EM USO": "Em uso", "EM ESTOQUE": "Em estoque", "MANUTENCAO": "Em manutenção",
            "EM MANUTENÇÃO": "Em manutenção", "BAIXA": "Baixa", "BAIXADO": "Baixa"}.get(str(value or "").strip().upper(), str(value or "").strip())


def create_history(conn, equipamento_id, previous, next_item, event, details=None, sector="TI"):
    details = details or {}
    record = {
        "equipamentoId": str(equipamento_id), "patrimonio": next_item.get("patrimonio", ""),
        "datahora": f"{details['dataMovimento']}T12:00:00" if details.get("dataMovimento") else datetime.now().astimezone().isoformat(),
        "tipoEvento": event, "motivo": details.get("motivo", ""),
        "observacao": details.get("observacoes", ""),
    }
    for key in ("status", "responsavel", "setor", "local", "termo"):
        record[key + "Anterior"] = previous.get(key, "")
        record[key + "Novo"] = next_item.get(key, "")
    conn.execute("INSERT INTO movimentacoes (equipamento_id, dados, setor) VALUES (%s, %s, %s)", (equipamento_id, Jsonb(record), sector))


@app.get("/api/equipamentos")
@app.get("/api/marketing/equipamentos")
def list_equipment(request: Request):
    sector = "MARKETING" if request.url.path.startswith("/api/marketing/") else "TI"
    require_sector(request, sector)
    with connection() as conn:
        return [equipment_row(row) for row in conn.execute("""
            SELECT * FROM equipamentos
            WHERE setor = %s AND NOT excluido
            ORDER BY
                CASE WHEN patrimonio ~ '^[[:alnum:]]+-[0-9]+$'
                    THEN substring(patrimonio FROM '[0-9]+$')::numeric END DESC NULLS LAST,
                CASE WHEN patrimonio ~* '^GTMTI-[0-9]+$' THEN 0 ELSE 1 END,
                length(substring(patrimonio FROM '[0-9]+$')),
                patrimonio,
                id
        """, (sector,)).fetchall()]


@app.post("/api/equipamentos")
@app.post("/api/marketing/equipamentos")
def create_equipment(item: dict, request: Request):
    sector = "MARKETING" if request.url.path.startswith("/api/marketing/") else "TI"
    require_sector(request, sector)
    validate_fields(item, ("patrimonio", "categoria", "marca", "modelo"))
    if not str(item.get("patrimonio", "")).strip():
        raise HTTPException(400, "Informe o patrimônio interno.")
    if not item.get("categoria") or not item.get("marca") or not item.get("modelo"):
        raise HTTPException(400, "Informe o tipo de ativo, a marca e o modelo.")
    item = {**item, "status": "Em estoque", "responsavel": "", "email": "", "telefone": "", "setor": "", "termo": "N/A"}
    try:
        with connection() as conn:
            row = conn.execute("INSERT INTO equipamentos (patrimonio, dados, setor) VALUES (%s, %s, %s) RETURNING *", (str(item["patrimonio"]).strip(), Jsonb(item), sector)).fetchone()
            result = equipment_row(row)
            create_history(conn, row["id"], {}, result, "CADASTRO", sector=sector)
            return result
    except psycopg.errors.UniqueViolation:
        raise HTTPException(409, "Já existe um equipamento cadastrado com esse patrimônio.")


@app.put("/api/equipamentos/{equipment_id}")
@app.put("/api/marketing/equipamentos/{equipment_id}")
def update_equipment(equipment_id: int, item: dict, request: Request):
    valid_id(equipment_id)
    validate_fields(item)
    sector = "MARKETING" if request.url.path.startswith("/api/marketing/") else "TI"
    require_sector(request, sector)
    with connection() as conn:
        row = conn.execute("SELECT * FROM equipamentos WHERE id = %s AND setor = %s AND NOT excluido FOR UPDATE", (equipment_id, sector)).fetchone()
        if not row:
            raise HTTPException(404, "Equipamento não encontrado.")
        previous = equipment_row(row)
        item = {**previous, **item, "id": str(equipment_id)}
        validate_fields(item, ("patrimonio", "categoria", "marca", "modelo"))
        try:
            saved = conn.execute("UPDATE equipamentos SET patrimonio = %s, dados = %s WHERE id = %s RETURNING *", (str(item.get("patrimonio", "")).strip(), Jsonb(item), equipment_id)).fetchone()
        except psycopg.errors.UniqueViolation:
            raise HTTPException(409, "Já existe um equipamento cadastrado com esse patrimônio.")
        result = equipment_row(saved)
        create_history(conn, equipment_id, previous, result, "Edição do cadastro", sector=sector)
        return result


