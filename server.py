@app.post("/api/movimentacoes")
@app.post("/api/marketing/movimentacoes")
def move_equipment(data: dict, request: Request):
    sector = "MARKETING" if request.url.path.startswith("/api/marketing/") else "TI"
    require_sector(request, sector)
    validate_fields(data)
    valid_id(data.get("equipamentoId"))
    try:
        date.fromisoformat(data.get("dataMovimento", ""))
    except ValueError:
        raise HTTPException(400, "Informe a data da movimentação.")
    new_status = clean_status(data.get("statusNovo"))
    event = {"Em uso": "USO", "Em estoque": "ESTOQUE", "Em manutenção": "MANUTENCAO", "Baixa": "BAIXA"}.get(new_status)
    if not event:
        raise HTTPException(400, "Selecione um status válido.")
    if new_status == "Baixa" and not str(data.get("motivo", "")).strip():
        raise HTTPException(400, "Informe o motivo da baixa.")
    with connection() as conn:
        row = conn.execute("SELECT * FROM equipamentos WHERE id = %s AND setor = %s AND NOT excluido FOR UPDATE", (data.get("equipamentoId"), sector)).fetchone()
        if not row:
            raise HTTPException(404, "Equipamento não encontrado.")
        previous = equipment_row(row)
        in_use = new_status == "Em uso"
        updated = {**previous, "status": new_status, "responsavel": data.get("responsavel", "").strip() if in_use else "",
                   "email": data.get("email", "").strip() if in_use else "", "telefone": data.get("telefone", "").strip() if in_use else "",
                   "setor": data.get("setor", "").strip() if in_use else "", "local": "" if new_status == "Baixa" else data.get("local", "").strip(),
                   "termo": (data.get("termo") or "N/A") if in_use else "N/A"}
        conn.execute("UPDATE equipamentos SET dados = %s WHERE id = %s", (Jsonb(updated), row["id"]))
        create_history(conn, row["id"], previous, updated, event, data, sector=sector)
        return updated


