@app.post("/api/import-local")
def import_local(data: dict, request: Request):
    require_sector(request, "TI")
    equipamentos = data.get("equipamentos", [])
    movimentacoes = data.get("movimentacoes", [])
    if not isinstance(equipamentos, list) or not isinstance(movimentacoes, list):
        raise HTTPException(400, "Formato de importação inválido.")
    if len(equipamentos) + len(movimentacoes) > 200:
        raise HTTPException(422, "Importe no maximo 200 registros por vez.")
    for item in equipamentos:
        validate_fields(item, ("patrimonio", "categoria", "marca", "modelo"))
    for record in movimentacoes:
        validate_fields(record)
    with connection() as conn:
        if conn.execute("SELECT 1 FROM equipamentos WHERE setor = 'TI' LIMIT 1").fetchone():
            return {"importado": False}
        ids = {}
        for item in equipamentos:
            old_id = str(item.get("id", ""))
            item.pop("id", None)
            patrimonio = str(item.get("patrimonio", "")).strip()
            if not patrimonio:
                continue
            item.setdefault("status", "Em estoque")
            row = conn.execute("INSERT INTO equipamentos (patrimonio, dados, setor) VALUES (%s, %s, 'TI') ON CONFLICT DO NOTHING RETURNING *", (patrimonio, Jsonb(item))).fetchone()
            if row:
                ids[old_id] = row["id"]
        for record in movimentacoes:
            equipment_id = ids.get(str(record.get("equipamentoId", "")))
            if equipment_id:
                record.pop("id", None)
                record.pop("histid", None)
                conn.execute("INSERT INTO movimentacoes (equipamento_id, dados, setor) VALUES (%s, %s, 'TI')", (equipment_id, Jsonb(record)))
    return {"importado": True, "equipamentos": len(ids)}


